"""ml/dataset_builder.py — Process PCAP + session JSON into ML training datasets.

Reads network capture files and session metadata generated by capture_session.py
or gen_synthetic.py, filters and labels traffic according to session intervals,
and exports:
    1. ml/data/dataset_flow.csv:      5-second per-flow window statistical features.
    2. ml/data/dataset_device.csv:    30-second per-device window aggregated features.
    3. ml/data/dataset_sequences.npz: Early flow packet sequences (first 20 packets, shape (N, 20, 2)).
    4. ml/data/meta.json:             Dataset metadata (batch IDs, class names, sample counts).

Designed for Edge AI traffic classification on Raspberry Pi.
"""

from __future__ import annotations

import argparse
import glob
import ipaddress
import json
import logging
from math import isinf, isnan
from pathlib import Path
from typing import Any, Dict, List, NamedTuple, Optional, Sequence, Tuple

import numpy as np
import pandas as pd
from scapy.all import PcapReader, rdpcap
from scapy.layers.inet import ICMP, IP, TCP, UDP
from scapy.layers.inet6 import IPv6
from scapy.layers.l2 import Ether

from ml.features import WindowStats

logger = logging.getLogger("ml.dataset_builder")

# Ports to ignore (infrastructure / control traffic)
IGNORED_PORTS = {53, 5353, 123, 67, 68}


class PacketRecord(NamedTuple):
    """Normalized metadata for a single network packet."""

    time: float
    wirelen: int
    direction: int  # +1 for forward (LAN -> WAN), -1 for backward (WAN -> LAN)
    flow_key: str
    mac: str


class AppInterval(NamedTuple):
    """Trimmed time window and label for an active app session."""

    t_start: float
    t_end: float
    label: str
    interval_id: int


class DatasetBuilder:
    """Builds tabular and sequence datasets from session PCAPs and metadata."""

    def __init__(
        self,
        lan_subnet: str = "192.168.4.0/24",
        window_flow: float = 5.0,
        window_device: float = 30.0,
        output_dir: str | Path = "ml/data",
    ) -> None:
        """Initialize DatasetBuilder with network parameters and window lengths.

        Args:
            lan_subnet: IPv4/IPv6 CIDR subnet representing local network devices.
            window_flow: Non-overlapping window duration in seconds for flow-level features.
            window_device: Window duration in seconds for device-level features.
            output_dir: Directory where generated datasets and metadata will be saved.
        """
        self.lan_network = ipaddress.ip_network(lan_subnet, strict=False)
        self.window_flow = float(window_flow)
        self.window_device = float(window_device)
        self.output_dir = Path(output_dir)

        # Output accumulation across all processed sessions
        self.flow_rows: List[Dict[str, Any]] = []
        self.device_rows: List[Dict[str, Any]] = []
        self.sequences_list: List[np.ndarray] = []
        self.sequences_labels: List[str] = []
        self.batch_ids: List[str] = []
        self.class_names_set: set[str] = set()

    def is_lan_ip(self, ip_str: str) -> bool:
        """Check whether an IP string belongs to the configured LAN subnet."""
        if not ip_str:
            return False
        try:
            return ipaddress.ip_address(ip_str) in self.lan_network
        except ValueError:
            return False

    def load_session_metadata(self, session_path: Path) -> Optional[Dict[str, Any]]:
        """Load and parse session JSON metadata.

        Args:
            session_path: Path to session_*.json file.

        Returns:
            Dictionary with session metadata, or None if reading/parsing fails.
        """
        try:
            content = session_path.read_text(encoding="utf-8")
            return json.loads(content)
        except Exception as exc:
            logger.error("Failed to read session file %s: %s", session_path, exc)
            return None

    def locate_pcap_file(
        self, session_path: Path, session_data: Dict[str, Any]
    ) -> Optional[Path]:
        """Locate the PCAP file referenced by a session JSON.

        Args:
            session_path: Path to the session JSON file.
            session_data: Parsed session metadata dictionary.

        Returns:
            Resolved Path to the PCAP file if found, otherwise None.
        """
        pcap_name = session_data.get("pcap_file")

        candidate_paths: List[Path] = []
        if pcap_name:
            candidate_paths.append(session_path.parent / pcap_name)
            candidate_paths.append(Path(pcap_name))

        # Fallback heuristic: look for capture_*.pcap in the same directory
        batch_name = session_data.get("batch", "")
        if batch_name:
            candidate_paths.extend(session_path.parent.glob(f"capture_{batch_name}_*.pcap"))
            candidate_paths.extend(session_path.parent.glob(f"*{batch_name}*.pcap"))
        candidate_paths.extend(session_path.parent.glob("*.pcap"))

        for cand in candidate_paths:
            if cand.is_file():
                return cand.resolve()

        return None

    def extract_app_intervals(
        self, session_data: Dict[str, Any]
    ) -> List[AppInterval]:
        """Extract trimmed start and end timestamps for each application in the session.

        Trims cooldown / margin seconds from start and end as defined by session['trim_s'].

        Args:
            session_data: Parsed session dictionary containing 'apps' list and 'trim_s'.

        Returns:
            List of valid AppInterval objects.
        """
        trim_s = float(session_data.get("trim_s", 15.0))
        intervals: List[AppInterval] = []

        apps = session_data.get("apps", [])
        for idx, app_record in enumerate(apps):
            raw_start = float(app_record.get("t_start", 0.0))
            raw_end = float(app_record.get("t_end", 0.0))
            label = str(app_record.get("app", "unknown")).strip()

            t_start = raw_start + trim_s
            t_end = raw_end - trim_s

            if t_end > t_start:
                intervals.append(AppInterval(t_start=t_start, t_end=t_end, label=label, interval_id=idx))
            else:
                logger.warning(
                    "App interval for '%s' too short after trimming (%.1fs - %.1fs <= 0s), skipping interval.",
                    label,
                    raw_end,
                    raw_start,
                )

        intervals.sort(key=lambda x: x.t_start)
        return intervals

    def parse_packet(
        self, pkt: Any, app_intervals: Sequence[AppInterval]
    ) -> Optional[Tuple[PacketRecord, AppInterval]]:
        """Filter packet, determine 5-tuple direction, wire length, and match app interval.

        Args:
            pkt: Scapy Packet object.
            app_intervals: Active trimmed app intervals in chronological order.

        Returns:
            Tuple of (PacketRecord, matching AppInterval) if packet passes filter, else None.
        """
        # Timestamp
        try:
            pkt_time = float(pkt.time)
        except Exception:
            return None

        # Match app interval; packets in cooldown or outside are ignored
        matching_interval: Optional[AppInterval] = None
        for interval in app_intervals:
            if interval.t_start <= pkt_time <= interval.t_end:
                matching_interval = interval
                break
        if matching_interval is None:
            return None

        # Filter ICMP
        if pkt.haslayer(ICMP):
            return None

        # Protocol check (TCP or UDP)
        if TCP in pkt:
            proto = "tcp"
            sport = int(pkt[TCP].sport)
            dport = int(pkt[TCP].dport)
        elif UDP in pkt:
            proto = "udp"
            sport = int(pkt[UDP].sport)
            dport = int(pkt[UDP].dport)
        else:
            return None

        # Filter ignored ports (DNS, mDNS, NTP, DHCP)
        if sport in IGNORED_PORTS or dport in IGNORED_PORTS:
            return None

        # Extract IP addresses
        if IP in pkt:
            src_ip = str(pkt[IP].src)
            dst_ip = str(pkt[IP].dst)
        elif IPv6 in pkt:
            src_ip = str(pkt[IPv6].src)
            dst_ip = str(pkt[IPv6].dst)
        else:
            return None

        src_in_lan = self.is_lan_ip(src_ip)
        dst_in_lan = self.is_lan_ip(dst_ip)

        # Determine direction: +1 if src_ip in LAN (forward/up), else -1 (backward/down)
        direction = 1 if src_in_lan else -1

        # Canonical 5-tuple flow key: client (LAN) -> server (WAN)
        if src_in_lan and not dst_in_lan:
            c_ip, c_port = src_ip, sport
            s_ip, s_port = dst_ip, dport
        elif dst_in_lan and not src_in_lan:
            c_ip, c_port = dst_ip, dport
            s_ip, s_port = src_ip, sport
        else:
            # Both or neither in LAN: deterministic tie-breaker
            if (src_ip, sport) <= (dst_ip, dport):
                c_ip, c_port = src_ip, sport
                s_ip, s_port = dst_ip, dport
            else:
                c_ip, c_port = dst_ip, dport
                s_ip, s_port = src_ip, sport

        flow_key = f"{c_ip}:{c_port}-{s_ip}:{s_port}/{proto}"

        # Extract MAC address of LAN device
        mac = "unknown"
        if Ether in pkt:
            if src_in_lan:
                mac = str(pkt[Ether].src).lower()
            elif dst_in_lan:
                mac = str(pkt[Ether].dst).lower()
            else:
                mac = str(pkt[Ether].src).lower()
        else:
            mac = c_ip

        # Original wire length (wirelen on-the-wire before snaplen truncation)
        wirelen = getattr(pkt, "wirelen", None)
        if wirelen is None or wirelen <= 0:
            wirelen = len(pkt)
        wirelen = int(wirelen)

        return (
            PacketRecord(
                time=pkt_time,
                wirelen=wirelen,
                direction=direction,
                flow_key=flow_key,
                mac=mac,
            ),
            matching_interval,
        )

    def process_session(self, session_path: Path) -> bool:
        """Process a single session JSON and its corresponding PCAP file.

        Args:
            session_path: Path to session metadata JSON.

        Returns:
            True if session was successfully parsed and added, False otherwise.
        """
        logger.info("Processing session: %s", session_path)
        session_data = self.load_session_metadata(session_path)
        if not session_data:
            return False

        batch_id = str(session_data.get("batch", session_path.stem))
        pcap_file = self.locate_pcap_file(session_path, session_data)
        if not pcap_file or not pcap_file.is_file():
            logger.warning(
                "PCAP file for session '%s' does not exist. Skipping.",
                session_path.name,
            )
            return False

        app_intervals = self.extract_app_intervals(session_data)
        if not app_intervals:
            logger.warning("No valid trimmed app intervals found in %s", session_path)
            return False

        logger.info("Reading packets from PCAP: %s", pcap_file)

        # Buffers for current session per app interval:
        # interval_id -> flow_key -> list of PacketRecord
        interval_flows: Dict[int, Dict[str, List[PacketRecord]]] = {
            interval.interval_id: {} for interval in app_intervals
        }
        # interval_id -> mac -> list of PacketRecord
        interval_devices: Dict[int, Dict[str, List[PacketRecord]]] = {
            interval.interval_id: {} for interval in app_intervals
        }
        interval_map: Dict[int, AppInterval] = {
            interval.interval_id: interval for interval in app_intervals
        }

        pkt_count = 0
        matched_count = 0
        try:
            with PcapReader(str(pcap_file)) as reader:
                for pkt in reader:
                    pkt_count += 1
                    res = self.parse_packet(pkt, app_intervals)
                    if res is None:
                        continue
                    prec, interval = res
                    matched_count += 1

                    # Store in flow container
                    flow_dict = interval_flows[interval.interval_id]
                    if prec.flow_key not in flow_dict:
                        flow_dict[prec.flow_key] = []
                    flow_dict[prec.flow_key].append(prec)

                    # Store in device container
                    dev_dict = interval_devices[interval.interval_id]
                    if prec.mac not in dev_dict:
                        dev_dict[prec.mac] = []
                    dev_dict[prec.mac].append(prec)
        except Exception as exc:
            logger.error("Error reading PCAP %s: %s", pcap_file, exc)
            return False

        logger.info(
            "Parsed %d total packets, %d matched active app intervals in session %s",
            pkt_count,
            matched_count,
            batch_id,
        )

        # Generate dataset items for each interval
        self.batch_ids.append(batch_id)
        for interval in app_intervals:
            self.class_names_set.add(interval.label)
            flows_in_interval = interval_flows[interval.interval_id]
            devices_in_interval = interval_devices[interval.interval_id]

            # 1. Flow windows & First-20 sequences
            self._process_interval_flows(
                flows=flows_in_interval,
                label=interval.label,
                batch_id=batch_id,
            )

            # 2. Device windows
            self._process_interval_devices(
                devices=devices_in_interval,
                interval_start=interval.t_start,
                label=interval.label,
                batch_id=batch_id,
            )

        return True

    def _process_interval_flows(
        self,
        flows: Dict[str, List[PacketRecord]],
        label: str,
        batch_id: str,
    ) -> None:
        """Process flows for an app interval into 5s windows and first-20 sequences."""
        for flow_key, packets in flows.items():
            # Edge case: Flow quá ngắn (< 3 packets) -> bỏ qua
            if len(packets) < 3:
                continue

            # Ensure chronological order
            packets.sort(key=lambda p: p.time)

            # First-20 sequence for early CNN classification
            seq_matrix = np.zeros((20, 2), dtype=np.float32)
            first_20 = packets[:20]
            for i, p in enumerate(first_20):
                # Signed packet wire length normalized by MTU (1500 bytes)
                norm_size = (p.direction * p.wirelen) / 1500.0
                # Inter-arrival time (ms)
                if i == 0:
                    iat_ms = 0.0
                else:
                    iat_ms = max(0.0, (p.time - first_20[i - 1].time) * 1000.0)
                norm_iat = float(np.log1p(iat_ms))

                seq_matrix[i, 0] = np.float32(norm_size)
                seq_matrix[i, 1] = np.float32(norm_iat)

            self.sequences_list.append(seq_matrix)
            self.sequences_labels.append(label)

            # Non-overlapping 5-second windows
            t_flow_start = packets[0].time
            windows: Dict[int, List[PacketRecord]] = {}
            for p in packets:
                w_idx = int((p.time - t_flow_start) // self.window_flow)
                if w_idx not in windows:
                    windows[w_idx] = []
                windows[w_idx].append(p)

            # Extract dest_port and transport proto from canonical flow_key
            dest_port = 0
            proto = ""
            try:
                endpoints, proto = flow_key.split("/")
                _, server_endpoint = endpoints.split("-")
                _, dport_str = server_endpoint.rsplit(":", 1)
                dest_port = int(dport_str)
            except Exception:
                dest_port = 0
                proto = ""

            # Compute WindowStats for each window with packets
            for _, win_pkts in sorted(windows.items(), key=lambda x: x[0]):
                ws = WindowStats()
                for p in win_pkts:
                    ws.update(size=p.wirelen, direction=p.direction, timestamp=p.time)

                row = ws.extract(dest_port=dest_port, transport=proto)
                row["label"] = label
                row["batch_id"] = batch_id
                row["flow_key"] = flow_key
                self.flow_rows.append(row)

    def _process_interval_devices(
        self,
        devices: Dict[str, List[PacketRecord]],
        interval_start: float,
        label: str,
        batch_id: str,
    ) -> None:
        """Process device packets into 30s aggregate windows."""
        for mac, packets in devices.items():
            if not packets:
                continue

            packets.sort(key=lambda p: p.time)

            # Slice into 30s non-overlapping windows relative to interval start
            windows: Dict[int, List[PacketRecord]] = {}
            for p in packets:
                w_idx = int((p.time - interval_start) // self.window_device)
                if w_idx not in windows:
                    windows[w_idx] = []
                windows[w_idx].append(p)

            for _, win_pkts in sorted(windows.items(), key=lambda x: x[0]):
                # Upload (+1) / Download (-1) counts & bytes
                pkts_up = sum(1 for p in win_pkts if p.direction > 0)
                pkts_down = sum(1 for p in win_pkts if p.direction < 0)
                bytes_up = sum(p.wirelen for p in win_pkts if p.direction > 0)
                bytes_down = sum(p.wirelen for p in win_pkts if p.direction < 0)

                total_bytes = bytes_up + bytes_down
                total_pkts = pkts_up + pkts_down

                bytes_down_ratio = float(bytes_down / total_bytes) if total_bytes > 0 else 0.0
                pkt_down_ratio = float(pkts_down / total_pkts) if total_pkts > 0 else 0.0

                active_flows = {p.flow_key for p in win_pkts}
                n_active_flows = len(active_flows)

                dev_row = {
                    "total_bytes_up": int(bytes_up),
                    "total_bytes_down": int(bytes_down),
                    "total_pkts_up": int(pkts_up),
                    "total_pkts_down": int(pkts_down),
                    "bytes_down_ratio": bytes_down_ratio,
                    "pkt_down_ratio": pkt_down_ratio,
                    "log1p_bytes_up": float(np.log1p(bytes_up)),
                    "log1p_bytes_down": float(np.log1p(bytes_down)),
                    "log1p_pkts_up": float(np.log1p(pkts_up)),
                    "log1p_pkts_down": float(np.log1p(pkts_down)),
                    "log1p_total_bytes": float(np.log1p(total_bytes)),
                    "log1p_total_pkts": float(np.log1p(total_pkts)),
                    "n_active_flows": int(n_active_flows),
                    "label": label,
                    "batch_id": batch_id,
                    "mac": mac,
                }
                self.device_rows.append(dev_row)

    def export(self) -> Dict[str, Path]:
        """Export accumulated datasets to CSV, NPZ, and JSON files.

        Returns:
            Dictionary mapping dataset name to exported Path.
        """
        self.output_dir.mkdir(parents=True, exist_ok=True)

        flow_csv_path = self.output_dir / "dataset_flow.csv"
        device_csv_path = self.output_dir / "dataset_device.csv"
        seq_npz_path = self.output_dir / "dataset_sequences.npz"
        meta_json_path = self.output_dir / "meta.json"

        # 1. Flow dataset CSV
        if self.flow_rows:
            df_flow = pd.DataFrame(self.flow_rows)
        else:
            # Empty DataFrame with canonical schema
            cols = list(WindowStats().extract().keys()) + ["label", "batch_id", "flow_key"]
            df_flow = pd.DataFrame(columns=cols)
        df_flow.to_csv(flow_csv_path, index=False)
        logger.info("Saved flow dataset (%d rows) to %s", len(df_flow), flow_csv_path)

        # 2. Device dataset CSV
        if self.device_rows:
            df_device = pd.DataFrame(self.device_rows)
        else:
            dev_cols = [
                "total_bytes_up",
                "total_bytes_down",
                "total_pkts_up",
                "total_pkts_down",
                "bytes_down_ratio",
                "pkt_down_ratio",
                "log1p_bytes_up",
                "log1p_bytes_down",
                "log1p_pkts_up",
                "log1p_pkts_down",
                "log1p_total_bytes",
                "log1p_total_pkts",
                "n_active_flows",
                "label",
                "batch_id",
                "mac",
            ]
            df_device = pd.DataFrame(columns=dev_cols)
        df_device.to_csv(device_csv_path, index=False)
        logger.info("Saved device dataset (%d rows) to %s", len(df_device), device_csv_path)

        # 3. First-20 Sequences NPZ
        if self.sequences_list:
            sequences_arr = np.stack(self.sequences_list, axis=0).astype(np.float32)
            labels_arr = np.array(self.sequences_labels, dtype=str)
        else:
            sequences_arr = np.zeros((0, 20, 2), dtype=np.float32)
            labels_arr = np.array([], dtype=str)

        np.savez_compressed(
            seq_npz_path,
            sequences=sequences_arr,
            labels=labels_arr,
        )
        logger.info(
            "Saved sequences dataset shape %s to %s",
            sequences_arr.shape,
            seq_npz_path,
        )

        # 4. Metadata JSON
        class_names = sorted(list(self.class_names_set))
        flow_counts = (
            df_flow["label"].value_counts().to_dict() if not df_flow.empty else {}
        )
        device_counts = (
            df_device["label"].value_counts().to_dict() if not df_device.empty else {}
        )
        seq_counts = (
            pd.Series(labels_arr).value_counts().to_dict()
            if len(labels_arr) > 0
            else {}
        )

        meta = {
            "batch_ids": sorted(list(set(self.batch_ids))),
            "class_names": class_names,
            "total_flow_windows": len(df_flow),
            "total_device_windows": len(df_device),
            "total_sequences": len(sequences_arr),
            "n_samples_flow": {str(k): int(v) for k, v in flow_counts.items()},
            "n_samples_device": {str(k): int(v) for k, v in device_counts.items()},
            "n_samples_sequences": {str(k): int(v) for k, v in seq_counts.items()},
            "window_flow_seconds": self.window_flow,
            "window_device_seconds": self.window_device,
        }
        meta_json_path.write_text(json.dumps(meta, indent=2, ensure_ascii=False), encoding="utf-8")
        logger.info("Saved dataset metadata to %s", meta_json_path)

        return {
            "flow_csv": flow_csv_path,
            "device_csv": device_csv_path,
            "sequences_npz": seq_npz_path,
            "meta_json": meta_json_path,
        }


def collect_session_files(session_inputs: Sequence[str]) -> List[Path]:
    """Collect and resolve session JSON file paths from CLI arguments and globs.

    Args:
        session_inputs: List of file paths or glob patterns.

    Returns:
        Sorted list of unique Path objects pointing to existing session JSON files.
    """
    found: set[Path] = set()
    for item in session_inputs:
        p = Path(item)
        if p.is_file():
            found.add(p.resolve())
            continue

        # Check glob pattern
        if any(char in item for char in ["*", "?", "["]):
            matches = glob.glob(item)
            for m in matches:
                mp = Path(m)
                if mp.is_file():
                    found.add(mp.resolve())

    return sorted(list(found))


def build_parser() -> argparse.ArgumentParser:
    """Construct CLI argument parser for dataset builder."""
    p = argparse.ArgumentParser(
        prog="python3 -m ml.dataset_builder",
        description="Build flow, device, and sequence ML datasets from PCAP and session JSON.",
    )
    p.add_argument(
        "--sessions",
        "--session",
        dest="sessions",
        nargs="+",
        required=True,
        help="Path(s) or glob pattern(s) to session JSON metadata files.",
    )
    p.add_argument(
        "--lan-subnet",
        default="192.168.4.0/24",
        help="Local network subnet in CIDR format (default: 192.168.4.0/24).",
    )
    p.add_argument(
        "--window-flow",
        type=float,
        default=5.0,
        help="Flow window duration in seconds (default: 5.0).",
    )
    p.add_argument(
        "--window-device",
        type=float,
        default=30.0,
        help="Device window duration in seconds (default: 30.0).",
    )
    p.add_argument(
        "--output-dir",
        default="ml/data",
        help="Directory to save output CSV, NPZ, and JSON files (default: ml/data).",
    )
    p.add_argument(
        "-v",
        "--verbose",
        action="store_true",
        help="Enable detailed DEBUG logging.",
    )
    return p


def main() -> None:
    """CLI entry point for dataset builder."""
    parser = build_parser()
    args = parser.parse_args()

    log_level = logging.DEBUG if args.verbose else logging.INFO
    logging.basicConfig(
        level=log_level,
        format="%(asctime)s [%(levelname)s] %(name)s: %(message)s",
    )

    session_files = collect_session_files(args.sessions)
    if not session_files:
        logger.warning("No session JSON files matched pattern: %s", args.sessions)
        return

    logger.info("Found %d session file(s) to process.", len(session_files))

    builder = DatasetBuilder(
        lan_subnet=args.lan_subnet,
        window_flow=args.window_flow,
        window_device=args.window_device,
        output_dir=args.output_dir,
    )

    processed_count = 0
    for s_path in session_files:
        if builder.process_session(s_path):
            processed_count += 1

    logger.info("Successfully processed %d/%d sessions.", processed_count, len(session_files))
    builder.export()
    logger.info("Dataset construction complete!")


if __name__ == "__main__":
    main()
